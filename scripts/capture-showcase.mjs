import { chromium, expect } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';
import fs from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve('docs/media');
await fs.mkdir(path.join(output, 'frames'), { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'en-US' });
  await page.goto(process.env.SHOWCASE_URL || 'http://127.0.0.1:4173');
  await page.screenshot({ path: path.join(output, 'landing.png'), fullPage: true });
  await page.screenshot({ path: path.join(output, 'frames/01.png') });
  const rows = ['Asset ID,Name,Serial,Location,Department', ...Array.from({ length: 245 }, (_, i) => `PC-${String(i + 1).padStart(3,'0')},Engineering PC ${i+1},CZC${90000+i},Engineering Room,Engineering`)];
  await page.getByLabel('Choose a CSV or Excel file').setInputFiles({ name: 'assets.csv', mimeType: 'text/csv', buffer: Buffer.from(rows.join('\n')) });
  await expect(page.getByRole('img', { name: /Rendered label for/ })).toBeVisible();
  await expect(page.locator('.paper-label img')).toHaveCount(24);
  await page.screenshot({ path: path.join(output, 'workspace.png'), fullPage: true });
  await page.screenshot({ path: path.join(output, 'frames/02.png') });
  await page.getByRole('button', { name: 'Code 128', exact: true }).click();
  await expect(page.getByRole('img', { name: /Rendered label for/ })).toBeVisible();
  await expect(page.locator('.paper-label img')).toHaveCount(24);
  await page.screenshot({ path: path.join(output, 'barcode.png'), fullPage: true });
  await page.screenshot({ path: path.join(output, 'frames/03.png') });
  await page.getByRole('button', { name: 'QR code', exact: true }).click();
  await expect(page.locator('.paper-label img')).toHaveCount(24);
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'dark-workspace.png'), fullPage: true });
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  await page.locator('.preview-panel').scrollIntoViewIfNeeded();
  await expect(page.locator('.paper-label img')).toHaveCount(24);
  await page.screenshot({ path: path.join(output, 'frames/04.png') });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download PDF/ }).click();
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(output, 'frames/05.png') });
  const download = await downloadPromise;
  await download.saveAs(path.join(output, 'sample-labels.pdf'));
  const pdf = await PDFDocument.load(await fs.readFile(path.join(output, 'sample-labels.pdf')));
  if (pdf.getPageCount() !== 11) throw new Error('Showcase PDF expected 11 pages for 245 labels.');
  await page.screenshot({ path: path.join(output, 'frames/06.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({ path: path.join(output, 'mobile-workspace.png'), fullPage: true });
  console.log(`Captured actual app screenshots and ${pdf.getPageCount()}-page A4 sample PDF.`);
} finally { await browser.close(); }
